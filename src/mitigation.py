"""
src/mitigation.py
Automated Multi-Platform Defense & Incident Response Generator

Converts detected high-risk DNS anomalies into actionable firewall rules,
network IDS signatures, DNS sinkholes, and STIX 2.1 Threat Intelligence feeds.

Supported Export Formats:
1. Suricata / Snort 3 Network IDS Drop Rules (.rules)
2. BIND 9 / Unbound Response Policy Zone (RPZ) Zonefile (.rpz)
3. Pi-hole / AdGuard Home Blocklist (.txt)
4. Linux iptables / nftables Packet Filter Script (.sh)
5. Windows Defender Firewall PowerShell Script (.ps1)
6. OASIS STIX 2.1 Threat Intelligence JSON Bundle (.json)
"""

import json
import uuid
from src.domain_utils import normalize_domain
import os
import datetime
from typing import List, Dict
import pandas as pd


def generate_suricata_rules(anomalies: pd.DataFrame, base_sid: int = 3000001) -> str:
    """Generate Suricata / Snort network IDS detection rules."""
    lines = [
        "# ====================================================================",
        "# Automated Suricata / Snort IDS Signatures",
        "# Generated by DNS Anomaly Detector (v3 - Final Review Engine)",
        f"# Timestamp: {datetime.datetime.now().strftime('%Y-%m-%d %H:%M:%S')}",
        "# ====================================================================",
        ""
    ]
    sid = base_sid
    for _, row in anomalies.drop_duplicates("domain").iterrows():
        domain = normalize_domain(row.get("domain", ""))
        sev = str(row.get("severity", "HIGH")).upper()
        score = float(row.get("anomaly_score", 0.0))
        if not domain:
            continue

        rule = (
            f'drop dns $HOME_NET any -> $EXTERNAL_NET 53 '
            f'(msg:"DNS-ANOMALY [{sev}] Algorithmic/Tunneling Domain: {domain} (Score={score:.2f})"; '
            f'dns.query; content:"{domain}"; nocase; startswith; endswith; '
            f'classtype:trojan-activity; sid:{sid}; rev:1;)'
        )
        lines.append(rule)
        sid += 1

    return "\n".join(lines)


def generate_bind_rpz_zone(anomalies: pd.DataFrame) -> str:
    """Generate BIND 9 / Unbound Response Policy Zone (RPZ) sinkhole file."""
    now_serial = datetime.datetime.now().strftime("%Y%m%d01")
    lines = [
        "; ====================================================================",
        "; BIND 9 / Unbound Response Policy Zone (RPZ) Threat Sinkhole",
        f"; Serial: {now_serial}",
        "; ====================================================================",
        "$TTL 300",
        f"@ IN SOA localhost. root.localhost. ( {now_serial} 3600 600 86400 300 )",
        "  IN NS  localhost.",
        ""
    ]
    for _, row in anomalies.drop_duplicates("domain").iterrows():
        domain = normalize_domain(row.get("domain", ""))
        if not domain:
            continue
        # CNAME . signifies NXDOMAIN response (sinkhole)
        lines.append(f"{domain} CNAME .")
        lines.append(f"*.{domain} CNAME .")

    return "\n".join(lines)


def generate_pihole_blocklist(anomalies: pd.DataFrame) -> str:
    """Generate standard Pi-hole / AdGuard Home 0.0.0.0 blocklist format."""
    lines = [
        "# Pi-hole / AdGuard Home Threat Blocklist",
        f"# Generated: {datetime.datetime.now().strftime('%Y-%m-%d %H:%M:%S')}",
        f"# Total blocked domains: {len(anomalies)}",
        ""
    ]
    for _, row in anomalies.drop_duplicates("domain").iterrows():
        domain = normalize_domain(row.get("domain", ""))
        if domain:
            lines.append(f"0.0.0.0 {domain}")
    return "\n".join(lines)


def _dns_wire_hex(domain):
    wire = b"".join(bytes([len(label)]) + label.encode("ascii") for label in domain.split(".")) + b"\x00"
    return wire.hex()


def generate_iptables_script(anomalies: pd.DataFrame) -> str:
    """Generate Linux iptables / bash commands to drop packets targeting malicious domains."""
    lines = [
        "#!/usr/bin/env bash",
        "# Linux iptables / Netfilter Automated Drop Script",
        f"# Generated on {datetime.datetime.now().strftime('%Y-%m-%d %H:%M:%S')}",
        "# Matches plaintext UDP DNS only; use RPZ for resolver policy enforcement.",
        "set -e",
        "",
        "echo '[+] Applying DNS Anomaly Firewall Drops...'",
    ]
    seen_bases = set()
    for _, row in anomalies.drop_duplicates("domain").iterrows():
        domain = normalize_domain(row.get("domain", ""))
        reg_domain = domain
        target = reg_domain if reg_domain and reg_domain != "nan" else domain
        if target not in seen_bases:
            seen_bases.add(target)
            lines.append(
                f"iptables -I OUTPUT -p udp --dport 53 -m string --hex-string '|{_dns_wire_hex(target)}|' --algo bm -j REJECT --reject-with icmp-port-unreachable"
            )
            lines.append(
                f"iptables -I FORWARD -p udp --dport 53 -m string --hex-string '|{_dns_wire_hex(target)}|' --algo bm -j DROP"
            )

    lines.append("echo '[+] All anomalous DNS drop rules applied.'")
    return "\n".join(lines)


def generate_windows_firewall_script(anomalies: pd.DataFrame) -> str:
    """Generate Windows PowerShell script to block malicious IPs or configure hosts file."""
    lines = [
        "# Windows PowerShell Defense Script",
        f"# Generated: {datetime.datetime.now().strftime('%Y-%m-%d %H:%M:%S')}",
        "Write-Host '[*] Applying DNS sinkhole to hosts file and firewall...' -ForegroundColor Cyan",
        ' $HostsPath = Join-Path $env:SystemRoot "System32\\drivers\\etc\\hosts"',
        ""
    ]
    for _, row in anomalies.drop_duplicates("domain").iterrows():
        domain = normalize_domain(row.get("domain", ""))
        if domain:
            lines.append(f"Add-Content -Path $HostsPath -Value '0.0.0.0 {domain}' -Force")

    lines.append("ipconfig /flushdns")
    lines.append("Write-Host '[+] Windows DNS cache flushed and hosts sinkhole updated!' -ForegroundColor Green")
    return "\n".join(lines)


def generate_stix_bundle(anomalies: pd.DataFrame) -> dict:
    """Generate OASIS STIX 2.1 Threat Intelligence JSON bundle."""
    bundle_id = f"bundle--{uuid.uuid4()}"
    objects = []

    now_iso = datetime.datetime.now(datetime.timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")

    for idx, row in anomalies.drop_duplicates("domain").iterrows():
        domain = normalize_domain(row.get("domain", ""))
        score = float(row.get("anomaly_score", 0.0))
        sev = str(row.get("severity", "HIGH")).upper()
        ind_id = f"indicator--{uuid.uuid4()}"

        objects.append({
            "type": "indicator",
            "spec_version": "2.1",
            "id": ind_id,
            "created": now_iso,
            "modified": now_iso,
            "name": f"Malicious DNS Activity - {domain}",
            "description": f"Statistical DNS Anomaly Detector flagged domain with score {score:.4f} ({sev} severity).",
            "indicator_types": ["anomalous-activity"],
            "pattern": f"[domain-name:value = '{domain}']",
            "pattern_type": "stix",
            "valid_from": now_iso,

            "external_references": [
                {
                    "source_name": "mitre-attack",
                    "external_id": "T1568.002",
                    "url": "https://attack.mitre.org/techniques/T1568/002/"
                },
                {
                    "source_name": "mitre-attack",
                    "external_id": "T1071.004",
                    "url": "https://attack.mitre.org/techniques/T1071/004/"
                }
            ]
        })

    return {
        "type": "bundle",
        "id": bundle_id,
        "objects": objects,
    }


def export_all_mitigations(anomalies: pd.DataFrame, output_dir: str = "rules") -> Dict[str, str]:
    """
    Export all mitigation configurations to the specified directory.

    Returns
    -------
    Dict mapping rule type to written file path.
    """
    os.makedirs(output_dir, exist_ok=True)
    paths = {}

    # 1. Suricata
    suricata_path = os.path.join(output_dir, "suricata_dns_drop.rules")
    with open(suricata_path, "w", encoding="utf-8") as f:
        f.write(generate_suricata_rules(anomalies))
    paths["suricata"] = suricata_path

    # 2. BIND RPZ
    rpz_path = os.path.join(output_dir, "bind9_threat_sinkhole.rpz")
    with open(rpz_path, "w", encoding="utf-8") as f:
        f.write(generate_bind_rpz_zone(anomalies))
    paths["rpz"] = rpz_path

    # 3. Pi-hole
    pihole_path = os.path.join(output_dir, "pihole_blocklist.txt")
    with open(pihole_path, "w", encoding="utf-8") as f:
        f.write(generate_pihole_blocklist(anomalies))
    paths["pihole"] = pihole_path

    # 4. iptables
    iptables_path = os.path.join(output_dir, "firewall_drops.sh")
    with open(iptables_path, "w", encoding="utf-8") as f:
        f.write(generate_iptables_script(anomalies))
    paths["iptables"] = iptables_path

    # 5. Windows
    win_path = os.path.join(output_dir, "windows_sinkhole.ps1")
    with open(win_path, "w", encoding="utf-8") as f:
        f.write(generate_windows_firewall_script(anomalies))
    paths["windows"] = win_path

    # 6. STIX 2.1 JSON
    stix_path = os.path.join(output_dir, "threat_intelligence_stix.json")
    with open(stix_path, "w", encoding="utf-8") as f:
        json.dump(generate_stix_bundle(anomalies), f, indent=2)
    paths["stix"] = stix_path

    return paths


