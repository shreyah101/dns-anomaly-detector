"""
src/pcap_analyzer.py
PCAP / PCAPNG Network Packet Capture Parser and DNS Stream Extractor

Enables the DNS Anomaly Detector to ingest raw network packet capture
files (.pcap and .pcapng) generated by Wireshark, tcpdump, or Zeek.
Extracts Layer-7 DNS protocol attributes directly into standard DataFrames.
"""
from src.domain_utils import extract_domain


import os
import datetime
import pandas as pd
import numpy as np


def _extract_registered_domain(domain: str) -> str:
    """Extract registered domain (SLD.TLD) with robust fallback."""
    try:
        import tldextract
        ext = extract_domain(domain)
        if ext.domain and ext.suffix:
            return f"{ext.domain}.{ext.suffix}".lower()
        return domain.lower()
    except Exception:
        parts = domain.rstrip(".").split(".")
        if len(parts) >= 2:
            return ".".join(parts[-2:]).lower()
        return domain.lower()


def load_pcap_traffic(pcap_path: str, max_packets: int = None) -> pd.DataFrame:
    """
    Parse a PCAP or PCAPNG packet capture file and extract DNS queries into a DataFrame.

    Parameters
    ----------
    pcap_path : str
        Path to .pcap or .pcapng capture file.
    max_packets : int, optional
        Maximum packets to inspect.

    Returns
    -------
    pd.DataFrame with columns:
        timestamp, src_ip, dst_ip, sport, domain, registered_domain,
        qtype, qr, rcode, tx_id, packet_len, label
    """
    if not os.path.exists(pcap_path):
        raise FileNotFoundError(f"PCAP capture file not found: '{pcap_path}'")

    try:
        from scapy.utils import PcapReader
        from scapy.layers.dns import DNS, DNSQR
        from scapy.layers.inet import IP, UDP, TCP
        from scapy.layers.inet6 import IPv6
    except ImportError as e:
        raise ImportError(
            f"Scapy is required for PCAP parsing. Run 'pip install scapy'. Error: {e}"
        )

    records = []
    packet_count = 0

    try:
        reader = PcapReader(pcap_path)
    except Exception as exc:
        raise ValueError("Unable to read capture: expected a valid PCAP or PCAPNG file.") from exc
    with reader as pcap_reader:
        for pkt in pcap_reader:
            packet_count += 1
            if max_packets and packet_count > max_packets:
                break

            if not pkt.haslayer(DNS):
                continue

            dns = pkt[DNS]

            # Determine IP source & destination
            src_ip = "127.0.0.1"
            dst_ip = "127.0.0.1"
            sport = 0
            if pkt.haslayer(IP):
                src_ip = pkt[IP].src
                dst_ip = pkt[IP].dst
            elif pkt.haslayer(IPv6):
                src_ip = pkt[IPv6].src
                dst_ip = pkt[IPv6].dst

            if pkt.haslayer(UDP):
                sport = pkt[UDP].sport
            elif pkt.haslayer(TCP):
                sport = pkt[TCP].sport

            if not (pkt.haslayer(UDP) or pkt.haslayer(TCP)):
                continue
            transport = pkt[UDP] if pkt.haslayer(UDP) else pkt[TCP]
            if 53 not in (transport.sport, transport.dport):
                continue
            # Get timestamp
            try:
                pkt_time = float(pkt.time)
                dt = datetime.datetime.fromtimestamp(pkt_time, datetime.timezone.utc)
            except Exception:
                continue

            # QR: 0 = Query, 1 = Response
            qr_type = "RESPONSE" if dns.qr == 1 else "QUERY"

            # Response Code
            rcode_map = {0: "NOERROR", 1: "FORMERR", 2: "SERVFAIL", 3: "NXDOMAIN", 4: "NOTIMP", 5: "REFUSED"}
            rcode = rcode_map.get(dns.rcode, str(dns.rcode))

            # Query Question (DNSQR)
            if dns.qdcount > 0 and dns.qd is not None:
                qname = dns.qd[0].qname
                if isinstance(qname, bytes):
                    qname = qname.decode("utf-8", errors="ignore")
                domain = str(qname).rstrip(".").lower()

                # Query type mapping
                qtype_map = {1: "A", 28: "AAAA", 16: "TXT", 15: "MX", 5: "CNAME", 12: "PTR", 33: "SRV", 255: "ANY"}
                qtype = qtype_map.get(dns.qd[0].qtype, f"TYPE_{dns.qd[0].qtype}")

                if domain:
                    records.append({
                        "timestamp": dt,
                        "src_ip": src_ip,
                        "dst_ip": dst_ip,
                        "sport": sport,
                        "_client_port": transport.dport if dns.qr else transport.sport,
                        "domain": domain,
                        "registered_domain": _extract_registered_domain(domain),
                        "qtype": qtype,
                        "qr": qr_type,
                        "rcode": rcode,
                        "tx_id": hex(dns.id),
                        "packet_len": len(pkt),
                        "label": None,
                    })

    if not records:
        print(f"[!] Warning: No DNS packets detected in '{pcap_path}'")
        return pd.DataFrame(columns=[
            "timestamp", "src_ip", "dst_ip", "sport", "domain",
            "registered_domain", "qtype", "qr", "rcode", "tx_id", "packet_len", "label"
        ])

    # Join observed responses to requests; responses do not create extra queries
    # or turn the DNS resolver into a purported client.
    from collections import defaultdict, deque
    pending = defaultdict(deque)
    queries = []
    for record in sorted(records, key=lambda r: r["timestamp"]):
        response = record["qr"] == "RESPONSE"
        client, server = (record["dst_ip"], record["src_ip"]) if response else (record["src_ip"], record["dst_ip"])
        key = (client, server, record["_client_port"], record["tx_id"], record["domain"], record["qtype"])
        if response:
            if pending[key]:
                request = pending[key].popleft()
                request["response_code"] = record["rcode"]
                request["rcode"] = record["rcode"]
        else:
            record["response_code"] = None
            record["rcode"] = None
            pending[key].append(record)
            queries.append(record)
    columns = ["timestamp", "src_ip", "dst_ip", "sport", "domain", "registered_domain",
               "qtype", "qr", "rcode", "response_code", "tx_id", "packet_len", "label"]
    df = pd.DataFrame(queries, columns=columns)
    print(f"[+] Extracted {len(df)} DNS queries from '{pcap_path}'")
    return df


def generate_synthetic_pcap(output_path: str, n_records: int = 120) -> str:
    """
    Generate an authentic binary PCAP capture file populated with real UDP/DNS packets,
    including legitimate corporate traffic, DGA queries, DNS tunneling exfiltration,
    and regular C2 beaconing.

    Parameters
    ----------
    output_path : str
        Target PCAP file path.
    n_records : int
        Number of synthetic DNS packets to generate.

    Returns
    -------
    str : absolute path to generated PCAP.
    """
    try:
        from scapy.utils import wrpcap
        from scapy.layers.dns import DNS, DNSQR
        from scapy.layers.inet import IP, UDP, Ether
    except ImportError as e:
        raise ImportError(f"Scapy required: {e}")

    import random
    import string

    rng = random.Random(42)
    packets = []
    base_time = datetime.datetime(2024, 1, 1, tzinfo=datetime.timezone.utc)
    current_time = base_time.timestamp()

    # Client IP pool
    benign_ips = ["192.168.1.101", "192.168.1.102", "192.168.1.105", "192.168.1.110"]
    infected_ips = ["192.168.1.150", "192.168.1.151"]
    dns_server = "8.8.8.8"

    benign_domains = [
        "mail.google.com", "docs.google.com", "api.github.com",
        "raw.githubusercontent.com", "aws.amazon.com", "login.microsoftonline.com",
        "en.wikipedia.org", "cdn.cloudflare.net", "netflix.com",
        "slack.com", "zoom.us", "vit.ac.in", "stackoverflow.com"
    ]

    # 1. Build Benign Traffic Packets (~70% of total)
    n_benign = int(n_records * 0.7)
    for _ in range(n_benign):
        current_time += rng.expovariate(1.0 / 12.0)  # Poisson inter-arrival
        src_ip = rng.choice(benign_ips)
        domain = rng.choice(benign_domains)
        qtype = rng.choice([1, 1, 1, 28])  # mostly A, occasional AAAA

        pkt = (
            Ether() /
            IP(src=src_ip, dst=dns_server) /
            UDP(sport=rng.randint(49152, 65535), dport=53) /
            DNS(rd=1, qd=DNSQR(qname=domain, qtype=qtype))
        )
        pkt.time = current_time
        packets.append(pkt)

    # 2. Build Malicious DGA Queries (~15% of total)
    n_dga = int(n_records * 0.15)
    for _ in range(n_dga):
        current_time += rng.uniform(1.0, 5.0)
        src_ip = infected_ips[0]
        # random alphanumeric label
        rand_label = "".join(rng.choices(string.ascii_lowercase + string.digits, k=rng.randint(14, 22)))
        tld = rng.choice(["dga.tk", "botnet.pw", "malware.top", "phishing.cn"])
        domain = f"{rand_label}.{tld}"

        pkt = (
            Ether() /
            IP(src=src_ip, dst=dns_server) /
            UDP(sport=rng.randint(49152, 65535), dport=53) /
            DNS(rd=1, qd=DNSQR(qname=domain, qtype=1))
        )
        pkt.time = current_time
        packets.append(pkt)

    # 3. Build Malicious DNS Tunneling / Exfiltration Queries (~10% of total)
    n_tunnel = int(n_records * 0.10)
    secret_chunks = [
        "61646d696e2d70617373776f7264",  # 'admin-password' in hex
        "6b65793d5345435245545f544f4b454e",  # 'key=SECRET_TOKEN'
        "7373682d7273612d70726976617465",  # 'ssh-rsa-private'
        "557365723a20726f6f742048617368",  # 'User: root Hash'
    ]
    for i in range(n_tunnel):
        current_time += rng.uniform(0.5, 2.0)
        src_ip = infected_ips[1]
        chunk = rng.choice(secret_chunks) + f"{i:02x}"
        domain = f"{chunk}.tunnel.io"

        pkt = (
            Ether() /
            IP(src=src_ip, dst=dns_server) /
            UDP(sport=rng.randint(49152, 65535), dport=53) /
            DNS(rd=1, qd=DNSQR(qname=domain, qtype=16 if (i % 2 == 0) else 1))  # alternating TXT and A
        )
        pkt.time = current_time
        packets.append(pkt)

    # 4. Build C2 Periodic Beaconing Queries (Fixed 30s interval)
    beacon_start = base_time.timestamp()
    beacon_c2_domain = "c2-beacon.darkweb.biz"
    for step in range(n_records - n_benign - n_dga - n_tunnel):
        b_time = beacon_start + (step * 30.0) + rng.uniform(-0.4, 0.4)  # 30s period with tight jitter
        pkt = (
            Ether() /
            IP(src=infected_ips[0], dst=dns_server) /
            UDP(sport=51234, dport=53) /
            DNS(rd=1, qd=DNSQR(qname=beacon_c2_domain, qtype=1))
        )
        pkt.time = b_time
        packets.append(pkt)

    # Sort all packets by timestamp
    packets.sort(key=lambda p: float(p.time))

    # Write to PCAP file
    os.makedirs(os.path.dirname(os.path.abspath(output_path)), exist_ok=True)
    wrpcap(output_path, packets)
    print(f"[+] Generated authentic PCAP capture file: '{output_path}' ({len(packets)} packets)")
    return output_path


